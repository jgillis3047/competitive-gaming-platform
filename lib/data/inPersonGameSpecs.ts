const SPEC_BY_SLUG: Record<string, InPersonGameSpec> = Object.fromEntries(
  GAME_SPECS.map((s) => [s.slug, s])
);

export function getInPersonGameSpec(slug: string): InPersonGameSpec | null {
  if (RETIRED_IN_PERSON_SLUGS.has(slug)) return null;
  return SPEC_BY_SLUG[slug] ?? null;
}

export function listActiveInPersonGameSpecs(): InPersonGameSpec[] {
  return GAME_SPECS.filter((s) => !RETIRED_IN_PERSON_SLUGS.has(s.slug));
}

export function isWearableRunSlug(slug: string): boolean {
  const s = getInPersonGameSpec(slug);
  return s?.validatorKind === "wearable_sync";
}

export function isRetiredInPersonSlug(slug: string): boolean {
  return RETIRED_IN_PERSON_SLUGS.has(slug);
}
